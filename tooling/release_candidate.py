"""Project the public product scope from governed release inputs.

This module creates documentation, never support policy or release authority.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "docs/support-matrix.md"
TRUST_POLICY = "governance/release-candidate-certification-trust.json"


def trust_projection(root: Path) -> dict:
    policy = read(root, "governance/local-certification-trust.json")
    policy["bundle_path"] = "tests/certification/release-candidate/1.0/current"
    policy["closure_paths"] = [
        policy["bundle_path"] + "/**",
        "docs/migration/final-release-candidate.md",
        "docs/migration/records/final-release-candidate.yaml",
        "docs/migration/final-release-candidate-handoff.json",
        "docs/migration/ledger.md",
        "governance/change-control.json",
    ]
    return policy


def trust_text(root: Path) -> str:
    return json.dumps(trust_projection(root), indent=4) + "\n"


def read(root: Path, relative: str) -> dict:
    return json.loads((root / relative).read_text(encoding="utf-8"))


def cell(value: object) -> str:
    if isinstance(value, list):
        value = "; ".join(str(item) for item in value)
    return str(value).replace("|", "&#124;").replace("\n", " ")


def tool_resolution(root: Path, tools: dict, ref: str) -> object:
    if ref in {"cc", "cxx"}:
        return {
            name: (root / "bindings/cpp/profiles" / name)
            .read_text(encoding="utf-8")
            .strip()
            for name in ("windows-x86_64", "linux-x86_64")
        }
    if ref == "gradle":
        return (
            (root / "bindings/kotlin/gradle/wrapper/gradle-wrapper.properties")
            .read_text(encoding="utf-8")
            .strip()
        )
    alias = {"python": "python3", "maven": "mvn", "bundler": "bundle"}.get(ref, ref)
    tool = tools[alias]
    result = dict(tool["resolution"])
    if "release_constraint" in tool:
        result["release_constraint"] = tool["release_constraint"]
    if result["model"] == "repository_managed":
        import re

        content = (root / result["file"]).read_text(encoding="utf-8")
        match = re.search(result["file_pattern"], content)
        if match is None:
            raise ValueError("unresolved governed tool: " + ref)
        result["resolved_declaration"] = match[1]
    return result


def scope(root: Path) -> dict:
    policy = read(root, "governance/release-policy.json")
    manifest = read(root, "tests/certification/release-supply-chain/1.0/manifest.json")
    claims = {row["id"]: row for row in policy["support_claims"]}
    artifacts = manifest["artifacts"]
    identities = [row["id"] for row in artifacts]
    if len(set(identities)) != len(identities):
        raise ValueError("duplicate distribution identity")
    registered = {key for key in claims if key.startswith("binding:")}
    covered = [row["distribution_contract"]["support_claim"] for row in artifacts]
    if len(covered) != len(set(covered)) or set(covered) != registered:
        raise ValueError("distribution and binding claims are not a bijection")
    for artifact in artifacts:
        contract = artifact["distribution_contract"]
        claim = claims[contract["support_claim"]]
        if (
            contract["tier"] != claim["tier"]
            or contract["platforms"] != claim["platforms"]
        ):
            raise ValueError("distribution support differs from policy")
    return {"product": policy["product"], "claims": claims, "artifacts": artifacts}


def render(root: Path) -> str:
    data = scope(root)
    tools = read(root, "toolchain.json")["tools"]
    version = data["product"]["version"]
    lines = [
        "# STRling product and target support matrix",
        "",
        "<!-- Generated by tooling/release_candidate.py; edit governed inputs. -->",
        "",
        f"Product **{version}**. This table projects `governance/release-policy.json`,",
        "the release distribution manifest, exact target profiles and `toolchain.json`.",
        "Policy certification labels describe registered scope and historical acceptance;",
        "the final candidate requires its own fresh signed Full/Release certificate.",
        "No public 4.0.0 download or installation is claimed. Publication remains unauthorized.",
        "",
        "ABI 1 and transport protocol 1.0.0 are independent of the product version.",
        "Native packages require the matching 4.0.0 product marker as well as ABI/protocol",
        "compatibility. WASM clients use the authenticated 4.0.0 module factory.",
        "All listed CPU scopes are x86_64; no arm64, musl, macOS or universal-host claim",
        "follows from a package build, a runtime constraint or a Supported target engine.",
        "",
        "## Distribution routes",
        "",
        "| Binding | Package / route | Tier / registered evidence | OS / CPU scope | Native prerequisites / limits |",
        "| --- | --- | --- | --- | --- |",
    ]
    for artifact in data["artifacts"]:
        contract = artifact["distribution_contract"]
        claim = data["claims"][contract["support_claim"]]
        values = [
            claim["subject"],
            artifact["package_name"] + " / " + artifact["registry"],
            claim["tier"] + " / " + claim["certification_status"],
            claim["scope"],
            contract.get("native_runtime_prerequisites", []) + claim["limitations"],
        ]
        lines.append("| " + " | ".join(cell(value) for value in values) + " |")
    lines += [
        "",
        "## Exact runtime and toolchain eligibility",
        "",
        "These are eligibility declarations, not additional certified platform claims.",
        "Fresh build receipts record resolved versions and executable fingerprints.",
        "",
        "| Distribution | Registered tools and resolution |",
        "| --- | --- |",
    ]
    for artifact in data["artifacts"]:
        refs = artifact["toolchain_refs"]
        rows = []
        for ref in refs:
            rows.append(
                ref
                + ": `"
                + json.dumps(tool_resolution(root, tools, ref), sort_keys=True)
                + "`"
            )
        lines.append("| " + cell(artifact["surface"]) + " | " + cell(rows) + " |")
    lines += [
        "",
        "## Versioned target engines",
        "",
        "A target profile is independent of the host binding and its interpreter.",
        "Only exact registered runtime evidence establishes engine support; later",
        "versions and moving latest aliases are unsupported until separately qualified.",
        "",
        "| Profile | Revision | Exact identity | Scope / limitations |",
        "| --- | --- | --- | --- |",
    ]
    for identity, claim in sorted(data["claims"].items()):
        if not identity.startswith("target:"):
            continue
        relative = next(
            path
            for path in claim["evidence"]
            if path.startswith("spec/targets/profiles/")
        )
        read(root, relative)
        lines.append(
            "| "
            + " | ".join(
                cell(value)
                for value in [
                    identity,
                    claim["subject"],
                    "[" + relative + "](../" + relative + ")",
                    [claim["scope"], *claim["limitations"]],
                ]
            )
            + " |"
        )
    consumers = sum(
        len(row["distribution_contract"]["platforms"])
        for row in data["artifacts"]
        if row["distribution_contract"]["tier"] == "Supported"
    )
    lines += [
        "",
        "## Consumer and publication boundaries",
        "",
        f"The release manifest declares {consumers} Supported binding/platform clean-consumer",
        "scopes. Each requires an isolated staged-package install, native loading,",
        "canonical compile and mismatch rejection under the registered consumer verifier.",
        "Preview package assembly and fixture success do not promote a runtime or binding.",
        "TypeScript's declared Node >=22 <23 row remains distinct from historical Windows",
        "Node 24 observations and the bounded browser WASM harness.",
        "",
        "See [getting started](getting-started.md), the [migration guide](migration-guide.md)",
        "and [release policy](release-policy.md). Each binding guide describes imports,",
        "native discovery and proposed installation commands. Public registry ownership,",
        "trusted publishing, protected environments and exact publication authorization",
        "remain separately verified prerequisites; a package name is not ownership proof.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    action.add_argument("--write-trust", action="store_true")
    action.add_argument("--check-trust", action="store_true")
    args = parser.parse_args()
    selected = TRUST_POLICY if args.write_trust or args.check_trust else OUTPUT
    expected = trust_text(ROOT) if selected == TRUST_POLICY else render(ROOT)
    destination = ROOT / selected
    if args.write or args.write_trust:
        destination.write_text(expected, encoding="utf-8", newline="\n")
    passed = (
        destination.is_file() and destination.read_text(encoding="utf-8") == expected
    )
    print(
        json.dumps(
            {
                "status": "passed" if passed else "failed",
                "output": selected,
                "publication_authorized": False,
            },
            sort_keys=True,
        )
    )
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
